# ------------------------------------------------ الدستور كما يقرؤه النموذج

CONSTITUTION = """دستور المونتاج (مُلزِم — لا يجوز مخالفته مهما كان):

١. **قاعدة الثلاث ثوان**: لا يبقى أي مشهد ساكنًا أكثر من ثلاث ثوان. إن طال
   المعنى فقسّمه إلى لقطات متتابعة. هذه القاعدة فوق كل اعتبار.

٢. **المونتاج يتبع الكلام كلمة بكلمة**: كل لقطة مرتبطة بالعبارة التي تُقال
   أثناءها. حين يقول الراوي «القطار» يجب أن يكون القطار على الشاشة في تلك
   اللحظة، لا قبلها بعشر ثوان ولا بعدها.

٣. **ارسم ولا تكتب**: اللقطة رسم يشرح المعنى، لا سطر نصّ. إن ذُكر قطار
   فارسم قطارًا يسير على قضبان وينفث دخانًا. إن ذُكرت بطارية فارسم بطارية
   تتدفّق منها الأيونات. النصّ تسمية قصيرة تحت الرسم، لا بديل عنه.

٤. **لقطة واحدة = فكرة واحدة**: لا تحشر فكرتين في لقطة. إن كان في الجملة
   فكرتان فهما لقطتان.

٥. **الحركة لا تتوقّف**: حتى اللقطة القصيرة فيها شيء يتحرّك — دخان يتصاعد،
   إلكترون يدور، سهم يتقدّم. الشاشة الجامدة موت بصري.

٦. **لا تكرار متجاور**: لا تضع الرسم نفسه في لقطتين متتاليتين. غيّر الزاوية
   أو الرسم أو أضف عنصرًا.

٧. **إيقاع متنوّع**: لا تجعل كل اللقطات بالطول نفسه. نوّع بين القصيرة
   (ثانية ونصف) والطويلة (ثلاث ثوان) بحسب ثقل المعنى.

٨. **اتجاه عربي**: التسلسل والأسهم من اليمين إلى اليسار، كاتجاه القراءة.

٩. **الرسم يسبق الكلمة بلحظة**: يظهر قبل نطق الكلمة بجزء من الثانية، فالعين
   أسرع من الأذن.

١٠. **لا لقطة بلا سبب**: كل لقطة تضيف فهمًا. إن لم تُضف شيئًا فاحذفها ومدّد
    التي قبلها (ضمن حدّ الثلاث ثوان)."""


def prompt_block(catalog_names):
    """نصّ الدستور + قائمة الرسوم المتاحة، كما يُحقن في طلب النموذج."""
    names = "، ".join(catalog_names)
    return f"""{CONSTITUTION}

الرسوم المتاحة (استعمل أسماءها كما هي بالإنجليزية فقط):
{names}

لكل قسم أعطِ قائمة «beats»: لقطة لكل فكرة، بالترتيب الذي تُقال به.
كل لقطة:
  "say"   : العبارة من نصّ التعليق التي تُقال أثناء هذه اللقطة (انسخها حرفيًا)
  "draw"  : اسم رسم واحد من القائمة أعلاه
  "label" : تسمية عربية قصيرة جدًا (كلمتان أو ثلاث) أو اتركها فارغة

عدد اللقطات في القسم = عدد الأفكار فيه. قسم مدّته دقيقة يحتاج نحو
عشرين لقطة أو أكثر. لا تبخل بعددها: القليل منها يعني شاشة جامدة."""


# ------------------------------------------------------------ الفرض بالكود

def enforce(beats, total, max_hold=MAX_HOLD, min_hold=MIN_HOLD):
    """يضمن أن كل لقطة ضمن الحدّ، ويكسر الطويلة، ويملأ الفجوات.

    يأخذ لقطات لكل منها 'at' (بداية بالثواني) ويعيد لقطات لكل منها
    'at' و'dur' بحيث: لا تداخل، ولا فجوة، ولا لقطة تتجاوز max_hold.
    """
    if total <= 0:
        return []

    clean = []
    for b in beats:
        try:
            at = max(0.0, float(b.get("at", 0.0)))
        except (TypeError, ValueError):
            continue
        if at < total:
            clean.append({**b, "at": at})
    clean.sort(key=lambda b: b["at"])

    if not clean:
        clean = [{"at": 0.0, "draw": "pulse", "label": ""}]
    clean[0]["at"] = 0.0

    # ندمج اللقطات الأقصر من الحدّ الأدنى في سابقتها
    merged = [clean[0]]
    for b in clean[1:]:
        if b["at"] - merged[-1]["at"] < min_hold:
            continue
        merged.append(b)

    out = []
    for i, b in enumerate(merged):
        end = merged[i + 1]["at"] if i + 1 < len(merged) else total
        span = end - b["at"]
        if span <= 0:
            continue

        # القاعدة الأولى: لا شيء يتجاوز ثلاث ثوان — نكسرها، لكن بإيقاع متنوّع
        cuts = _slice(span, i, max_hold, min_hold)
        # نُدوّر المواضع ثم نشتقّ المدد من الفروق، فلا يتسرّب خطأ التقريب:
        # تدوير كل مدّة على حدة كان يُنقِص ثوانيَ مِللية تتراكم على طول القسم
        ats = [round(b["at"] + off, 3) for off, _ in cuts] + [round(b["at"] + span, 3)]
        for p in range(len(cuts)):
            out.append({
                "at": ats[p],
                "dur": round(ats[p + 1] - ats[p], 3),
                "draw": b.get("draw") or "pulse",
                "label": b.get("label", "") if p == 0 else "",
                "say": b.get("say", "") if p == 0 else "",
                "split": p > 0,                        # جزء مكمّل لا لقطة جديدة
            })
    return _break_monotony(out, min_hold)


def _break_monotony(beats, min_hold, run=3, tol=0.15, floor=0.6):
    """يكسر سلاسل اللقطات المتساوية الطول.

    اللقطات الأقصر من الحدّ لا تُقسَّم أصلًا، فإن جاءت عبارات النموذج
    متساوية الطول خرج المونتاج منتظمًا رغم احترامه للقاعدة. هنا نقسم
    الوسطى من كل سلسلة متماثلة إلى نصفين — والنصفان داخل العبارة نفسها
    فلا ينفكّ القطع عن الكلمة، والثاني مُعلَّم split فلا تتكرّر التسمية.
    """
    i, out = 0, list(beats)
    k = 0
    while k + run <= len(out):
        window = out[k:k + run]
        d0 = window[0]["dur"]
        if all(abs(b["dur"] - d0) <= tol for b in window) and d0 / 2 >= floor:
            mid = k + run // 2
            b = out[mid]
            # نُنوّع نسبة القَسم وإلا خرجت كل الأنصاف بالطول نفسه،
            # فاستبدلنا انتظامًا بانتظام آخر
            half = round(b["dur"] * (0.5, 0.40, 0.58)[i % 3], 3)
            if min(half, b["dur"] - half) < floor:
                half = round(b["dur"] / 2, 3)
            second = {**b, "at": round(b["at"] + half, 3),
                      "dur": round(b["dur"] - half, 3),
                      "label": "", "say": "", "split": True}
            out[mid] = {**b, "dur": half}
            out.insert(mid + 1, second)
            k = mid + 2
            i += 1
        else:
            k += 1
    if i:
        print(f"[montage] كُسرت {i} سلسلة متماثلة الإيقاع")
    return out


# نمط الإيقاع: نِسَب تتكرّر دوريًا فتتنوّع أطوال اللقطات بلا عشوائية.
# الانتظام الميكانيكي (كل لقطة ٣٫٠٠s بالضبط) علامة هواة بقدر اللقطة الساكنة
# الطويلة؛ الأذن تتعب من النبض الثابت كما تتعب العين من الصورة الجامدة.
_PULSE = (1.00, 0.74, 0.90, 0.64, 0.82, 1.00, 0.70)


def _slice(span, seed, max_hold, min_hold):
    """يقسّم مدّة إلى أجزاء متنوّعة الأطوال، لا يتجاوز أيٌ منها الحدّ.

    يعيد [(الإزاحة، المدّة), …] ومجموع المدد = span بالضبط.
    """
    if span <= max_hold + 1e-9:
        return [(0.0, span)]

    # أطول جزء يساوي (span/n) × (أعلى وزن ÷ متوسّط الأوزان)، فنحسب n ابتداءً
    # من هذه النسبة. الزيادة الخطوة-خطوة كانت تعجز عن اللحاق في الأقسام
    # الطويلة فتسقط إلى التقسيم المتساوي — أي إلى الانتظام الذي نهرب منه.
    ratio = max(_PULSE) / (sum(_PULSE) / len(_PULSE))
    n = max(1, int(-(-span * ratio // max_hold)))   # ceil
    for _ in range(8):                              # نزيد الأجزاء حتى تسع الحدّ
        w = [_PULSE[(seed + k) % len(_PULSE)] for k in range(n)]
        s = sum(w)
        parts = [span * x / s for x in w]
        if max(parts) <= max_hold + 1e-9 and min(parts) >= min(min_hold, span / n):
            break
        n += 1
    else:
        parts = [span / n] * n                      # تعذّر التنويع: تقسيم متساوٍ

    out, t = [], 0.0
    for k, part in enumerate(parts):
        # آخر جزء يُنهي المدّة بالضبط فلا يتراكم خطأ التقريب
        part = span - t if k == len(parts) - 1 else part
        out.append((t, part))
        t += part
    return out


def violations(beats, max_hold=MAX_HOLD):
    """يعيد قائمة المخالفات — تُستعمل في الاختبار وفي سجلّ التشغيل."""
    bad = []
    for i, b in enumerate(beats):
        if b.get("dur", 0) > max_hold + 1e-6:
            bad.append(f"اللقطة {i} مدّتها {b['dur']:.2f}s > {max_hold}s")
    for i in range(1, len(beats)):
        prev, cur = beats[i - 1], beats[i]
        gap = cur["at"] - (prev["at"] + prev["dur"])
        if abs(gap) > 0.05:
            bad.append(f"فجوة/تداخل {gap:+.2f}s قبل اللقطة {i}")
        if (not cur.get("split") and cur.get("draw") == prev.get("draw")):
            bad.append(f"تكرار متجاور للرسم «{cur.get('draw')}» عند اللقطة {i}")
    return bad


def animated_ratio(beats, animated_names):
    """نسبة اللقطات التي فيها حركة حقيقية."""
    if not beats:
        return 0.0
    n = sum(1 for b in beats if b.get("draw") in animated_names)
    return n / len(beats)
