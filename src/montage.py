"""
دستور المونتاج — قواعد مُلزِمة، مكتوبة للنموذج ومفروضة بالكود.

القاعدة التي لا تُخالَف مهما كانت الصعوبة: **لا لقطة تبقى ساكنة أكثر من
ثلاث ثوان**. النموذج قد ينساها، والكود لا ينسى: `enforce` يكسر أي لقطة
تتجاوز الحدّ قبل أن تصل إلى الرسم أصلًا.

هذا الملف مصدر الحقيقة الوحيد لقواعد الإيقاع: النصّ الذي يُرسل إلى
النموذج والثوابت التي يتحقّق منها الكود يخرجان من هنا معًا، فلا يفترقان.
"""

# ------------------------------------------------------------ الثوابت

MAX_HOLD = 3.0          # الحدّ الأقصى المطلق لأي لقطة — إلزامي
MIN_HOLD = 1.1          # أقصر من هذا يصير وميضًا مُربِكًا
LEAD_IN = 0.18          # الرسم يسبق الكلمة قليلًا: العين قبل الأذن
